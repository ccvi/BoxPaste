import AppKit
import Foundation

// ============================================================
// 剪贴板监听
//
// 为什么是轮询而不是事件通知：macOS 没有"剪贴板变化"的系统通知。
// NSPasteboard.changeCount 是唯一的官方信号，只能定时去看。
// 0.35s 是权衡结果：再密一点，读图片的进程唤醒次数肉眼可见地涨；
// 再疏一点，复制完立刻按热键会看不到刚复制的那条。
//
// 三条"不记录"的规矩（都在 makeItem 里）：
//   ① 密码管理器标记为保密/临时的内容不记（org.nspasteboard.* 那三个类型）；
//   ② 我们自己写回剪贴板的动作不记（不然粘贴一次就多一条，越用越脏）；
//   ③ 空内容不记。
// ============================================================

final class ClipboardWatcher {

    /// 密码管理器（1Password、Bitwarden 等）约定的三个标记类型。
    private static let concealedTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
    ]

    var onCapture: (@MainActor (ClipItem) -> Void)?
    /// 图像上限：再大的基本不是"复制素材"而是"剪贴板里卡着一张巨图"，
    /// 硬记下来只会把 App Support 撑爆。
    private let maxImageBytes = 60 * 1024 * 1024
    /// 富文本上限：RTF/HTML 超过这个量级基本是"整个文档塞进了剪贴板"，
    /// 留着只会让 blobs 目录膨胀，不值得。
    private let maxRichBytes = 8 * 1024 * 1024
    private let thumbnailMaxSide: CGFloat = 600

    private let store: ClipStore
    private var timer: Timer?
    private var lastChangeCount: Int
    private var ignoredChangeCounts: Set<Int> = []
    /// 基础轮询间隔（设置项）
    private var baseInterval: TimeInterval = 0.35
    /// 面板是否开着。开着用基础间隔，收起来就放慢（见 effectiveInterval）
    private var isActive = false
    private var ignoreConcealed = true
    private var didPrimeClipboard = false

    /// 实际使用的轮询间隔。面板收起时放慢到 2.6 倍（下限 0.8s）：
    /// 隐藏状态下每秒 3 次的唤醒大多是白跑，省下来对电池有实际意义；
    /// 呼出面板时会立刻补扫一次（pollNow），不会漏掉刚复制的内容。
    private var effectiveInterval: TimeInterval {
        isActive ? baseInterval : max(baseInterval * 2.6, 0.8)
    }

    /// 暂停记录（隐私模式）。true 时轮询照常跑、changeCount 照常登记，
    /// 只是不收内容——这样恢复记录后不会把暂停期间的积压一股脑倒进历史。
    /// 刻意不持久化：重启默认恢复记录，避免"开关忘在暂停上，以为软件坏了"。
    var paused = false
    /// 是否连 RTF/HTML 一起记录（菜单栏可开关）。关掉时只留纯文本，
    /// 给"暂时不想让 blobs 长胖"的时刻用。
    var captureRichText = true

    init(store: ClipStore) {
        self.store = store
        self.lastChangeCount = NSPasteboard.general.changeCount
    }

    // ── 生命周期 ─────────────────────────────────────────────

    func start(interval: TimeInterval, ignoreConcealed: Bool) {
        self.ignoreConcealed = ignoreConcealed
        baseInterval = interval
        stop()

        // 启动时把当前剪贴板内容也收一条：用户按了热键却发现"刚复制的没在里面"
        // 是最容易让人怀疑工具坏了的一种体验。
        // 只做一次：改监听间隔会重新走 start()，不设这个标记的话每改一次
        // 就会把当前剪贴板又"重新收"一遍（去重能兜住，但那条会被无端提到最前）。
        if !didPrimeClipboard {
            didPrimeClipboard = true
            if let item = makeItem(from: .general) {
                lastChangeCount = NSPasteboard.general.changeCount
                emit(item)
            }
        }
        restartTimer()
    }

    /// 按当前 isActive 重建计时器。改间隔、切面板状态都走这里，
    /// 避免两处各自拼一遍 Timer 的配置（.common 模式漏了会表现为"拖拽时不记录"）。
    private func restartTimer() {
        timer?.invalidate()
        let timer = Timer(timeInterval: effectiveInterval, repeats: true) { [weak self] _ in
            self?.poll()
        }
        // .common 模式：拖拽输出、菜单弹出时默认模式会暂停，
        // 那些时刻恰好最需要监听到新复制的内容。
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    func stop() {
        timer?.invalidate()
        timer = nil
    }

    /// 面板显隐时切换轮询速度（见 effectiveInterval）。
    func setActive(_ active: Bool) {
        guard active != isActive else { return }
        isActive = active
        if timer != nil { restartTimer() }
    }

    /// 立刻扫一遍剪贴板。面板呼出时调用：慢速轮询期间复制的内容
    /// 不该等到下一拍才出现。
    func pollNow() {
        poll()
    }

    func updateInterval(_ interval: TimeInterval, ignoreConcealed: Bool) {
        self.ignoreConcealed = ignoreConcealed
        guard abs(interval - baseInterval) > 0.001 else { return }
        baseInterval = interval
        if timer != nil { restartTimer() }
    }

    /// 告诉它"这次变化是我们自己造成的"，跳过。
    /// Paster 写完剪贴板后立刻登记新的 changeCount。
    func ignore(changeCount: Int) {
        ignoredChangeCounts.insert(changeCount)
        lastChangeCount = changeCount
        // 防漏：一张剪贴板每次写入 changeCount 都会 +1，攒不了多少；
        // 但万一有人手动构造，这里兜一下，别让它无限涨。
        if ignoredChangeCounts.count > 64 { ignoredChangeCounts.removeAll() }
    }

    func syncChangeCount() {
        lastChangeCount = NSPasteboard.general.changeCount
    }

    // ── 轮询 ─────────────────────────────────────────────────

    private func poll() {
        let pasteboard = NSPasteboard.general
        let changeCount = pasteboard.changeCount
        guard changeCount != lastChangeCount else { return }
        lastChangeCount = changeCount

        if ignoredChangeCounts.remove(changeCount) != nil { return }

        // 隐私模式：只登记变化、不收内容（见 paused 的注释）
        if paused { return }

        guard let item = makeItem(from: pasteboard) else { return }
        emit(item)
    }

    /// Timer 与 NSPasteboard 都在主线程上，回调统一在主 isolate 上执行
    private func emit(_ item: ClipItem) {
        guard let onCapture else { return }
        MainActor.assumeIsolated { onCapture(item) }
    }

    // ── 内容提取 ─────────────────────────────────────────────

    private func makeItem(from pasteboard: NSPasteboard) -> ClipItem? {
        let typeNames = Set((pasteboard.types ?? []).map(\.rawValue))
        if ignoreConcealed && !typeNames.isDisjoint(with: Self.concealedTypes) { return nil }

        let frontmost = NSWorkspace.shared.frontmostApplication

        var item: ClipItem?
        if let files = fileURLs(from: pasteboard), !files.isEmpty {
            item = Self.fileItem(files)
        } else if let png = pngData(from: pasteboard) {
            item = Self.imageItem(png: png, store: store, maxImageBytes: maxImageBytes,
                                 thumbnailMaxSide: thumbnailMaxSide)
        } else if let text = pasteboard.string(forType: .string), !text.isEmpty {
            item = Self.textItem(text)
        }
        guard var result = item else { return nil }

        // 富文本：开关打开时把剪贴板里的 RTF/HTML 一并存档（RTF 文字处理软件给、
        // HTML 浏览器给，两个都要——写回时一起挂，目标应用爱挑哪种挑哪种）。
        if captureRichText {
            Self.attachRichText(to: &result, from: pasteboard, store: store,
                                maxBytes: maxRichBytes)
        }

        // 来源应用在**捕获时**取，不等到写盘：轮询有延迟，
        // 稍后再问"现在最前面是谁"很可能已经换人了。
        if let frontmost, frontmost.bundleIdentifier != Bundle.main.bundleIdentifier {
            result.sourceAppName = frontmost.localizedName
            result.sourceBundleID = frontmost.bundleIdentifier
        }
        return result
    }

    // ── 条目构造（静态：面板的"拖入收集"也用同一套，
    //    这样 hash 算法只有一份，去重不会因为入口不同而失效）────────

    static func textItem(_ text: String) -> ClipItem {
        let kind = ContentClassifier.kind(forText: text)
        return ClipItem(kind: kind,
                        text: text,
                        byteCount: text.utf8.count,
                        hash: Support.sha256("\(kind.rawValue):\(text)"))
    }

    /// 富文本存档的写盘队列（串行，qos 低）：RTF/HTML 可以到 8 MB，
    /// 放在主线程同步写会在复制大段网页内容时卡一下。
    private static let blobWriteQueue = DispatchQueue(label: "com.pcxx.boxpaste.blob-write",
                                                      qos: .utility)

    /// 把剪贴板里的 RTF/HTML 存进 blobs/ 并挂到条目上。
    /// 存档名由内容 hash 派生（同文本必然同名），与图像 blob 的命名规则一致。
    /// 抽成静态是因为自检要直接构造假剪贴板跑它，不走轮询。
    static func attachRichText(to item: inout ClipItem, from pasteboard: NSPasteboard,
                               store: ClipStore, maxBytes: Int) {
        guard item.kind == .text || item.kind == .link || item.kind == .color else { return }
        if let rtf = pasteboard.data(forType: .rtf), rtf.count <= maxBytes {
            let name = "\(item.hash).rtf"
            item.rtfBlobName = name
            // 名字先挂上、文件稍后到位：万一这毫秒级窗口里就粘贴，
            // Paster 读不到存档会安静退回纯文本（不会报错），可以接受。
            blobWriteQueue.async { try? store.writeBlob(data: rtf, name: name) }
        }
        if let html = pasteboard.data(forType: .html), html.count <= maxBytes {
            let name = "\(item.hash).html"
            item.htmlBlobName = name
            blobWriteQueue.async { try? store.writeBlob(data: html, name: name) }
        }
    }

    /// 等挂起的存档写盘全部完成。自检专用：断言"文件已落盘"必须等异步写完，
    /// 正常运行时不需要（读不到就按没有存档处理）。
    static func flushPendingBlobWrites() {
        blobWriteQueue.sync {}
    }

    static func fileItem(_ urls: [URL]) -> ClipItem {
        let paths = urls.map(\.path).joined(separator: "\n")
        return ClipItem(kind: .file,
                        text: paths,
                        byteCount: 0,
                        hash: Support.sha256("file:\(paths)"))
    }

    static func imageItem(png: Data, store: ClipStore,
                          maxImageBytes: Int = 60 * 1024 * 1024,
                          thumbnailMaxSide: CGFloat = 600) -> ClipItem? {
        guard png.count <= maxImageBytes else { return nil }
        let hash = Support.sha256("image:\(png)")
        let blobName = "\(hash).png"
        var item = ClipItem(kind: .image,
                            blobName: blobName,
                            byteCount: png.count,
                            hash: hash)
        // 尺寸与缩略图都走 ImageIO：只解缩略图那一档位图，不碰原尺寸。
        // 老写法 NSBitmapImageRep(data: png) 会把整张图解出来，复制一张 5K 截图
        // 的瞬间主线程要卡一下、峰值内存白涨几十 MB（捕获路径的性能热点）。
        if let probe = ImageTools.probe(png: png, maxPixel: Int(thumbnailMaxSide)) {
            item.pixelWidth = probe.pixelWidth
            item.pixelHeight = probe.pixelHeight
            if let thumb = probe.thumbnailPNG, let name = thumbnailName(for: blobName) {
                try? store.writeBlob(data: thumb, name: name)
            }
        }
        try? store.writeBlob(data: png, name: blobName)
        return item
    }

    /// 图像优先取 PNG；只有 TIFF 时转成 PNG 再存 ——
    /// 剪贴板里的 TIFF 是未压缩的，存下来能比 PNG 大一个数量级。
    private func pngData(from pasteboard: NSPasteboard) -> Data? {
        if let png = pasteboard.data(forType: .png) { return png }
        guard let tiff = pasteboard.data(forType: .tiff),
              let rep = NSBitmapImageRep(data: tiff),
              let png = rep.representation(using: .png, properties: [:]) else { return nil }
        return png
    }

    private func fileURLs(from pasteboard: NSPasteboard) -> [URL]? {
        let options: [NSPasteboard.ReadingOptionKey: Any] = [.urlReadingFileURLsOnly: true]
        guard let objects = pasteboard.readObjects(forClasses: [NSURL.self], options: options) else { return nil }
        let urls = objects.compactMap { $0 as? URL }
        return urls.isEmpty ? nil : urls
    }

    // ── 缩略图 ───────────────────────────────────────────────

    static func thumbnailName(for blobName: String) -> String? {
        guard !blobName.isEmpty else { return nil }
        let base = (blobName as NSString).deletingPathExtension
        let ext = (blobName as NSString).pathExtension
        return "\(base)@thumb.\(ext.isEmpty ? "png" : ext)"
    }
}
